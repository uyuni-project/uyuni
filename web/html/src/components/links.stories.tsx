import type { Meta, StoryObj } from "@storybook/react-webpack5";
import { action } from "storybook/actions";

import { ExampleRow, StripedExampleSection } from "components/example-layout";

import {
  ActionChainLink,
  ActionLink,
  ChannelAnchorLink,
  ChannelLink,
  PackageLink,
  SystemGroupLink,
  SystemLink,
} from "./links";

const meta = {
  title: "Components/Navigation/Links",
  component: ChannelLink,
  decorators: [
    (Story) => (
      <div
        onClickCapture={(event) => {
          const link = event.target instanceof Element ? event.target.closest("a") : null;
          if (link) {
            event.preventDefault();
            action("link clicked")(link.getAttribute("href"));
          }
        }}
      >
        <Story />
      </div>
    ),
  ],
  parameters: {
    docs: {
      description: {
        component:
          "Link helpers that build the canonical Uyuni URL for a channel, action, system, action chain, system group, or package. In Storybook, clicks log the destination instead of navigating.",
      },
    },
  },
  args: {
    id: 42,
    children: "Example channel",
    newWindow: false,
    className: "",
    title: "Open channel details",
  },
  argTypes: {
    id: {
      control: "text",
      description: "Entity identifier inserted into the generated Uyuni URL.",
    },
    newWindow: {
      control: "boolean",
      description: "Opens the target in a new window and adds `noopener noreferrer` when enabled.",
    },
    children: {
      control: "text",
      description: "Visible content of link variants that accept children.",
    },
    className: {
      control: false,
      description: "ChannelLink does not forward className. Other entity links support this prop.",
    },
    title: {
      control: "text",
      description: "Optional native tooltip text supported by `ChannelLink`.",
    },
  },
} satisfies Meta<typeof ChannelLink>;

export default meta;

type Story = StoryObj<typeof meta>;

export const Playground: Story = {};

export const EntityLinks: Story = {
  render: () => (
    <StripedExampleSection>
      <ExampleRow>
        <ChannelLink id={101}>Channel</ChannelLink>
        <ChannelAnchorLink id={101} />
        <ActionLink id={202}>Action</ActionLink>
        <SystemLink id={303}>System</SystemLink>
        <ActionChainLink id={404}>Action chain</ActionChainLink>
        <SystemGroupLink id={505}>System group</SystemGroupLink>
        <PackageLink id={606}>Package</PackageLink>
      </ExampleRow>
    </StripedExampleSection>
  ),
  parameters: {
    controls: { disable: true },
    docs: { description: { story: "Every entity-specific link generated by this module." } },
  },
};

export const NewWindow: Story = {
  args: {
    newWindow: true,
    children: "Channel in a new window",
  },
};
